#ifndef LLVM_LIB_TARGET_TRITON_TRITONSUBTARGET_H
#define LLVM_LIB_TARGET_TRITON_TRITONSUBTARGET_H

#include "TritonFrameLowering.h"
#include "TritonISelLowering.h"
#include "TritonInstrInfo.h"
#include "TritonRegisterInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "TritonGenSubtargetInfo.inc"

namespace llvm {
class StringRef;

class TritonSubtarget : public TritonGenSubtargetInfo {
  virtual void anchor();

protected:
  TritonInstrInfo InstrInfo;
  TritonRegisterInfo RegInfo;
  TritonISelLowering TLInfo;
  TritonFrameLowering FrameLowering;
  SelectionDAGTargetInfo TSInfo;

public:
  // Initializes the data members to match that of the specified triple.
  TritonSubtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU,
                  StringRef FS, StringRef ABIName, const TargetMachine &TM);

  // Parses features string setting specified subtarget options. Definition of
  // function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const TritonInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const TritonRegisterInfo *getRegisterInfo() const override {
    return &RegInfo;
  }
  const TritonISelLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const TritonFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  // Automatically generated by tblgen.
  bool enableMachineScheduler() const override { return true; }

  bool isRegisterReservedByUser(Register i) const override {
    // For now, no user-reserved registers
    return false;
  }

  bool enableSaveRestore() const {
    // For now, disable save/restore optimization
    return false;
  }
};

} // End llvm namespace

#endif
