#ifndef LLVM_LIB_TARGET_TRITON_MCTARGETDESC_TRITONINSTPRINTER_H
#define LLVM_LIB_TARGET_TRITON_MCTARGETDESC_TRITONINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class TritonInstPrinter : public MCInstPrinter {
public:
  TritonInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                    const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  void printRegName(raw_ostream &O, MCRegister Reg) override;
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O,
                    const char *Modifier = nullptr);
  void printBranchOperand(const MCInst *MI, uint64_t Address, unsigned OpNo,
                          raw_ostream &O);

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg, unsigned AltIdx = 0);
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &OS);
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_TRITON_MCTARGETDESC_TRITONINSTPRINTER_H
